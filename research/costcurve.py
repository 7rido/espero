"""#68: a cost curve by order size on Hyperliquid, from #51's book files (research/PREREGISTRATION_COSTCURVE.md).

    python research/costcurve.py report    # once; refuses unless the pre-registration is committed and unchanged

Reads exactly the files #51 fetched into data/bookwalk/ (the 20 days with 20 levels), fetches nothing and
writes nothing under data/. Output: research/costcurve_run.txt, costcurve_days.csv, costcurve_buckets.csv and
the generated espero/costcurve_table.py.
"""
from __future__ import annotations

import contextlib
import subprocess
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT)]

from espero import bookwalk as bw  # noqa: E402
from espero import costcurve as cc  # noqa: E402

COINS = ["BTC", "ETH", "SOL", "XRP", "DOGE", "LINK", "ADA", "AVAX", "BNB", "TRX", "LTC", "XLM", "HBAR", "kSHIB"]
DAYS = [d.strftime("%Y-%m-%d") for d in pd.date_range("2024-11-01", "2026-06-01", freq="MS")]   # 20, all 20 levels
DESIGN = DAYS[:10]                                                                              # through 2025-08-01
SEEN = {("SOL", "2025-06-01")}                                                                   # walked once before this test
LEVELS = 25
RAW = ROOT / "data" / "bookwalk"
PREREG = ROOT / "research" / "PREREGISTRATION_COSTCURVE.md"
OUTPUT = ROOT / "research" / "costcurve_run.txt"
DAYS_CSV = ROOT / "research" / "costcurve_days.csv"
BUCKETS_CSV = ROOT / "research" / "costcurve_buckets.csv"
TABLE_PY = ROOT / "espero" / "costcurve_table.py"


def path(coin: str, day: str) -> Path:
    return RAW / f"{coin}-{day}.csv.gz"


def committed_unchanged(p: Path) -> bool:
    rel = str(p.relative_to(ROOT))
    tracked = subprocess.run(["git", "ls-files", "--error-unmatch", rel], cwd=ROOT, capture_output=True)
    changed = subprocess.run(["git", "diff", "--quiet", "HEAD", "--", rel], cwd=ROOT)
    return tracked.returncode == 0 and changed.returncode == 0


def one_file(coin: str, day: str):
    sides = [f"{s}[{i}].{f}" for s in ("asks", "bids") for i in range(LEVELS) for f in ("price", "amount")]
    df = pd.read_csv(path(coin, day), usecols=sides + ["timestamp"])
    arr = {f"{s}_{f}": df[[f"{s}[{i}].{f}" for i in range(LEVELS)]].to_numpy(float)
           for s in ("asks", "bids") for f in ("price", "amount")}
    ok = bw.valid_snapshots(arr["asks_price"][:, 0], arr["bids_price"][:, 0])
    hours = pd.to_datetime(df["timestamp"].to_numpy(), unit="us").hour.to_numpy()[ok]
    levels = min(np.isfinite(arr["asks_price"][ok]).sum(axis=1).mean(), np.isfinite(arr["bids_price"][ok]).sum(axis=1).mean())
    by_size, buckets = cc.coin_day(arr["asks_price"][ok], arr["asks_amount"][ok], arr["bids_price"][ok], arr["bids_amount"][ok], hours)
    size_rows = [{"coin": coin, "day": day, "usd": usd, "snapshots": int(ok.sum()), "dropped": int((~ok).sum()),
                  "levels": round(float(levels), 2), **vals} for usd, vals in by_size.items()]
    bucket_rows = [{"coin": coin, "day": day, "bucket": b, "cost": c} for b, c in buckets.items()]
    return size_rows, bucket_rows


def write_table(scores) -> None:
    lines = ['"""Generated by research/costcurve.py (#68, research/PREREGISTRATION_COSTCURVE.md). Do not edit by hand.',
             "Per coin: c0 and k of cost = c0 + k * sqrt(usd / 10,000) in bps a leg on the design days, the reach in",
             'dollars, and the verdict; espero.costcurve.cost reads it and refuses what it does not cover."""',
             "TABLE = {"]
    for s in scores:
        lines.append(f"    {s['coin']!r}: {{'c0': {s['c0']:.4f}, 'k': {s['k']:.4f}, 'reach': {s['reach']}, "
                     f"'verdict': {s['verdict']!r}}},")
    lines.append("}")
    TABLE_PY.write_text("\n".join(lines) + "\n")


def report() -> None:
    rows, brows, missing = [], [], []
    for coin in COINS:
        for day in DAYS:
            if path(coin, day).exists():
                r, b = one_file(coin, day)
                rows += r
                brows += b
            else:
                missing.append((coin, day))
        print("read", coin, file=sys.stderr, flush=True)
    days = pd.DataFrame(rows)
    buckets = pd.DataFrame(brows)
    days.to_csv(DAYS_CSV, index=False, float_format="%.5f")
    buckets.to_csv(BUCKETS_CSV, index=False, float_format="%.5f")

    pd.set_option("display.width", 220, "display.max_rows", 400, "display.max_columns", 30)
    fmt = {c: "{:.3f}".format for c in ("cost", "low", "high", "design", "holdout")}
    fmt["unfillable"] = "{:.3f}".format
    print(f"#68: {len(COINS)} coins, {days['day'].nunique()} days {days['day'].min()} to {days['day'].max()}; "
          f"design through {DESIGN[-1]}; tolerance {cc.TOL_BPS} bps")
    scores = []
    for coin in COINS:
        s = cc.score(days, coin, DESIGN)
        scores.append(s)
        print(f"\n== {coin}: reach ${s['reach']:,}, {len(s['sizes'])} measured sizes; curve c0 {s['c0']:.3f} k {s['k']:.3f}; "
              f"design days at reach {s['design_days']}, holdout {s['holdout_days']}")
        print(f"   holdout error, bps: curve {s['err_curve']:.3f}  flat {s['err_flat']:.3f}  table {s['err_table']:.3f}"
              f"  -> {s['verdict']}")
        print(cc.size_table(days, coin, DESIGN).to_string(index=False, formatters=fmt))

    print("\n== Verdicts")
    summary = pd.DataFrame([{k: s[k] for k in ("coin", "reach", "c0", "k", "err_curve", "err_flat", "err_table", "verdict")}
                            for s in scores])
    print(summary.round(3).to_string(index=False))
    print("counts:", summary["verdict"].value_counts().to_dict())

    print("\n== The hour of the day: cost at $10,000 by four-hour UTC bucket, mean over days, information only")
    for coin in COINS:
        prof, ratio = cc.hour_profile(buckets, coin)
        print(f"{coin}: dearest/cheapest {ratio:.2f}  " + "  ".join(f"{b} {c:.3f} ({lo:.3f}-{hi:.3f})" for b, c, lo, hi
              in zip(prof["bucket"], prof["cost"], prof["low"], prof["high"])))

    print("\n== Floor-adjusted curve (#51's validation gap added), information only")
    for s in scores:
        if not s["reach"] or not np.isfinite(s["c0"]):
            print(f"{s['coin']}: no curve")
            continue
        at10 = float(cc.predict(s["c0"], s["k"], min(10_000, s["reach"])))
        atr = float(cc.predict(s["c0"], s["k"], s["reach"]))
        print(f"{s['coin']}: at ${min(10_000, s['reach']):,} {at10:.3f} -> {cc.adjusted(s['coin'], at10):.3f}; "
              f"at reach ${s['reach']:,} {atr:.3f} -> {cc.adjusted(s['coin'], atr):.3f}")

    print("\n== Coin-days and snapshots")
    once = days.drop_duplicates(["coin", "day"])
    print("missing files:", missing or "none")
    print("coin-days under 20 levels:", int((once["levels"] < 20).sum()), "of", len(once))
    print("snapshots:", int(once["snapshots"].sum()), "dropped:", int(once["dropped"].sum()))

    print("\n== Verdicts without the coin-day seen before this test")
    keep = [(c, d) not in SEEN for c, d in zip(days["coin"], days["day"])]
    alt = {s["coin"]: cc.score(days[keep], s["coin"], DESIGN)["verdict"] for s in scores}
    changed = [(s["coin"], s["verdict"], alt[s["coin"]]) for s in scores if alt[s["coin"]] != s["verdict"]]
    print("verdicts that change:", changed or "none")

    write_table(scores)


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command != "report":
        raise SystemExit(__doc__)
    if not committed_unchanged(PREREG):
        raise SystemExit("refused: research/PREREGISTRATION_COSTCURVE.md must be committed and unchanged")
    if OUTPUT.exists():
        raise SystemExit(f"refused: {OUTPUT.relative_to(ROOT)} exists; #68 runs once")
    buffer = OUTPUT.with_suffix(".part")
    with open(buffer, "w") as f, contextlib.redirect_stdout(f):
        report()
    buffer.rename(OUTPUT)
    print(OUTPUT.read_text())
