COINS = ["DOGE", "LINK", "WLD", "ARB", "OP", "TIA", "XTZ", "YFI"]
HL_COINS = ["DOGE", "LINK", "WLD", "ARB", "OP", "TIA"]
VOLUME_M = {"BTC": 13959, "ETH": 11175, "SOL": 2172, "XRP": 796, "DOGE": 600, "LINK": 126, "WLD": 82,
            "ARB": 41, "OP": 33, "TIA": 18, "XTZ": 6, "YFI": 2}       # March 2026, $M a day (the pre-registration)
PRIOR_TESTS = 41
CELLS = (8 + 6) * 10 * 4
BAR = 4.752

R.COINS = COINS
R.DAYS_DIR = ROOT / "data" / "markout_small" / "days"
R.RAW = ROOT / "data" / "markout_small" / "raw"
R.OUT_DAYS = ROOT / "research" / "markout_small_days.csv.gz"
