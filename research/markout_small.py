def job(kind, coin, day, liq):
    """Runs in a worker process: importing this module there applies the paths above."""
    return R.job(kind, coin, day, liq)


def fetch() -> None:
    (R.DAYS_DIR / "settle").mkdir(parents=True, exist_ok=True)
    lh = R.liq_hours()
    jobs = ([("V1", c, d) for d in R.V1_DAYS for c in COINS] + [("V2", c, d) for d in R.V2_DAYS for c in COINS]
            + [("H", c, d) for d in R.H_DAYS for c in HL_COINS] + [("B", c, d) for d in R.B_DAYS for c in COINS])
    done = []
    with ProcessPoolExecutor(R.WORKERS) as ex:
        futs = {ex.submit(job, k, c, d, lh.get(c) if k == "B" else None): (k, c, d) for k, c, d in jobs}
        for n, f in enumerate(as_completed(futs), 1):
            k, c, d = futs[f]
            try:
                r = f.result()
            except Exception as exc:
                r = {"job": k, "coin": c, "day": d, "status": f"error: {exc!r}"}
            done.append(r)
            if r["status"] != "cached":
                print(f"[{n}/{len(jobs)}] {k} {c} {d}: {r['status']}", flush=True)
    R.collect(done)


def validation(days: pd.DataFrame):
    """#39's rule, with V1 required only for coins that have V1 days."""
    keys = ["venue", "coin", "measure", "horizon", "cond", "level"]
    tables, ok, has = {}, {}, {}
    for name in ("V1", "V2"):
        d = days[days["set"] == name]
        a = R._all(R.stats(d[d["mid"] == "proxy"], None))
        b = R._all(R.stats(d[d["mid"] == "quote"], None))
        m = mk.agree(a, b, keys)
        tables[name] = m
        ok[name] = {(r.coin, r.measure, r.horizon): r.ok for r in m.itertuples()}
        has[name] = set(d["coin"])
    validated, v2_only = set(), []
    for c in COINS:
        sets = [v for v in ("V1", "V2") if c in has[v]]
        if "V2" not in sets:
            continue
        if "V1" not in sets:
            v2_only.append(c)
        taker = all(ok[v].get((c, "taker", 0), False) for v in sets)
        for h in mk.HORIZONS_S:
            if taker and all(ok[v].get((c, m, h), False) for v in sets for m in ("maker_opt", "maker_cons")):
                validated.add((c, h))
    return validated, tables, v2_only


def merge_table(main: pd.DataFrame, validated: set, replicated: bool) -> int:
    """Add this study's usable cells to espero/costs_table.py, keeping #39's."""
    sys.path.insert(0, str(ROOT))
    from espero import costs_table
    table = dict(costs_table.TABLE)
    keep = main["cond"].isin(["all", *mk.CONDITIONS]) & main["measure"].isin(["taker", "maker_cons"]) \
        & main["mean"].notna()
    taker_ok = {c for c, _ in validated}
    added = 0
    for r in main[keep].itertuples():
        if r.venue == "binance":
            good = replicated and ((r.coin in taker_ok) if r.measure == "taker" else ((r.coin, r.horizon) in validated))
            if not good:
                continue
        table[(r.venue, r.coin, r.measure, int(r.horizon), r.cond, r.level)] = round(float(r.mean), 4)
        added += 1
    lines = ['"""Generated by research/markout.py (#39) and research/markout_small.py (#41). Do not edit by hand.',
             "Keys: (venue, coin, measure, horizon_s, condition, level) -> mean bps;",
             'measure "taker" is the effective half-spread, "maker_cons" the back-of-queue markout."""',
             'SOURCE = "#39 and #41, research/PREREGISTRATION_MARKOUT.md and PREREGISTRATION_MARKOUT_SMALL.md"',
             "TABLE = {"]
    for k in sorted(table):
        lines.append(f"    {k!r}: {table[k]:.4f},")
    lines.append("}")
    R.TABLE_PY.write_text("\n".join(lines) + "\n")
    return added


def report() -> None:
    days = pd.read_csv(R.OUT_DAYS)
    print(f"#41 — markouts down the liquidity ladder. {len(days):,} day rows; bar t >= {BAR:.2f} "
          f"(computed {mk.bar(PRIOR_TESTS + CELLS):.3f}, N = {PRIOR_TESTS + CELLS})")
    meta = json.loads(R.MANIFEST.read_text()) if R.MANIFEST.exists() else {}
    print(f"dropped coin-days: {len(meta.get('dropped', []))}; job errors: {len(meta.get('errors', []))}")
    for e in meta.get("errors", [])[:20]:
        print("  error:", e)
    print("days per set:\n" + days.groupby(["set", "coin"])["day"].nunique().unstack().to_string())

    validated, vt, v2_only = validation(days)
    for name, m in vt.items():
        print(f"\n== Proxy validation {name}")
        print(R.show(m.rename(columns={"mean": "proxy", "mean_ref": "quote"}),
                     ["coin", "measure", "horizon", "proxy", "quote", "ok"]))
    print("validated (coin, horizon):", sorted(validated))
    print("validated on V2 alone (no V1 days):", v2_only)
    replicated, rt = R.replication(days)
    print("\n== Second source (Tardis trades vs archive aggTrades, V2 days)")
    print(R.show(rt.rename(columns={"mean": "tardis", "mean_ref": "archive"}),
                 ["coin", "measure", "horizon", "tardis", "archive", "ok"]))
    print("replicated:", replicated)

    main = pd.concat([R.stats(days[days["set"] == "B"], R.B_HALF), R.stats(days[days["set"] == "H"], R.H_HALF)],
                     ignore_index=True)
    main.to_csv(STATS, index=False, float_format="%.6g", compression="gzip")

    print("\n== Cost per leg (bps), 'all' cells")
    for v in ("binance", "hyperliquid"):
        fee = mk.FEES_BPS[v]
        print(f"-- {v}: taker fee {fee['taker']}, maker fee {fee['maker']}")
        for c in COINS:
            r = main[(main.venue == v) & (main.coin == c) & (main.cond == "all")]
            tk = r[r.measure == "taker"]
            if not len(tk):
                print(f"   {c}: no data")
                continue
            hs = float(tk["mean"].iloc[0])
            tag = "" if v != "binance" or any((c, h) in validated for h in mk.HORIZONS_S) else "  [proxy not validated]"
            print(f"   {c}: half-spread {hs:+.2f} (days {int(tk['days'].iloc[0])}), taker round trip "
                  f"{2 * (fee['taker'] + hs):.2f}{tag}")
            for h in mk.HORIZONS_S:
                o = r[(r.measure == "maker_opt") & (r.horizon == h)]
                k = r[(r.measure == "maker_cons") & (r.horizon == h)]
                print(f"      {h:>3}s  maker optimistic {R.fmt(float(o['mean'].iloc[0]))} (t {R.fmt(float(o['t'].iloc[0]))})"
                      f"   conservative {R.fmt(float(k['mean'].iloc[0]))} (t {R.fmt(float(k['t'].iloc[0]))})")

    print(f"\n== The answer — conservative maker markout net of the maker fee, t >= {BAR:.2f}, both halves")
    q = mk.q3(main, validated=validated, replicated=replicated, bar_t=BAR)
    top = q.sort_values("t_net", ascending=False).head(15)
    print(R.show(top, ["venue", "coin", "horizon", "cond", "level", "days", "net", "t_net", "net_h1", "net_h2",
                       "pass"]))
    pos_before_fee = q[q["mean"] > 0]
    print(f"cells examined: {len(q)}; passing: {int(q['pass'].sum())}; "
          f"positive before the fee (any t): {len(pos_before_fee)}")
    print("ANSWER:", "YES" if q["pass"].any() else "NO")

    print("\n== Information: the ladder (Binance, 'all', 60 s), majors from #39")
    both = pd.concat([pd.read_csv(MAJORS_STATS), main], ignore_index=True)
    lad = both[(both.venue == "binance") & (both.cond == "all")]
    rows = []
    for c, vol in sorted(VOLUME_M.items(), key=lambda x: -x[1]):
        g = lad[lad.coin == c]

        def cell(m, h):
            x = g[(g.measure == m) & (g.horizon == h)]["mean"]
            return float(x.iloc[0]) if len(x) else np.nan
        rows.append({"coin": c, "volume_$M": vol, "half_spread": cell("taker", 0), "opt_60s": cell("maker_opt", 60),
                     "cons_60s": cell("maker_cons", 60)})
    lt = pd.DataFrame(rows)
    print(lt.to_string(index=False, float_format=lambda x: f"{x:.2f}"))
    rk = lt.dropna()
    for col in ("half_spread", "opt_60s", "cons_60s"):
        rho = rk["volume_$M"].rank().corr(rk[col].rank())          # Spearman, without scipy
        print(f"  Spearman(log volume, {col}) = {rho:+.2f} over {len(rk)} coins")

    print("\n== Information: by print size (taker half-spread; optimistic maker 60 s)")
    sz = main[(main.cond == "size") & (((main.measure == "taker") & (main.horizon == 0))
                                       | ((main.measure == "maker_opt") & (main.horizon == 60)))]
    print(sz.pivot_table(index=["venue", "measure", "level"], columns="coin", values="mean").round(2).to_string())

    n = merge_table(main, validated, replicated)
    print(f"\nadded {n} cells to {R.TABLE_PY}")


if __name__ == "__main__":
    {"fetch": fetch, "report": report, "collect": R.collect}[sys.argv[1] if len(sys.argv) > 1 else "report"]()
